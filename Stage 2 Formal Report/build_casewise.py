"""Generate the report's matched overview and both 50-case appendices."""
import argparse

from phase_c_data import BANKS, FINAL, METHODS, REPORT, matched, paired


OUTPUT = REPORT / 'casewise.tex'


def render():
    lines = [
        r'% Generated by build_casewise.py from archived matched_case_metrics.csv.',
        r'\newcommand{\PhaseCMatchedRows}{%',
    ]
    for repeat in (1, 2):
        frame = matched(repeat)
        for method in METHODS:
            rows = frame[frame.method.eq(method)]
            budget = 100 * (rows.runtime_ms / rows.time_limit_ms).max()
            name = 'Integrated' if method == FINAL else method
            cells = [str(repeat), name, f'{rows.area.sum():,}', f'{rows.runtime_ms.sum()/1000:.3f}', f'{budget:.2f}\\%']
            lines.append(' & '.join(cells) + r' \\%')
    lines += [r'}', r'\newcommand{\PhaseCCasewise}{%', r'\begingroup\footnotesize',
              r'\setlength\tabcolsep{4pt}']
    group_header = ' & '.join(
        [r'\multicolumn{3}{c}{' + method + '}' for method in METHODS]
    )
    header = [
        r'\toprule', ' & & ' + group_header + r' \\',
        r'\cmidrule(lr){3-5}\cmidrule(lr){6-8}\cmidrule(lr){9-11}\cmidrule(lr){12-14}',
        'Case & Target & ' + ' & '.join(['Area', 'Delay', 'ms'] * len(METHODS)) + r' \\',
        r'\midrule',
    ]
    for repeat in (1, 2):
        frame = matched(repeat)
        area = paired(frame, 'area')
        delay = paired(frame, 'delay')
        time = paired(frame, 'runtime_ms')
        targets = paired(frame, 'target')
        if not targets.eq(targets[FINAL], axis=0).all().all():
            raise ValueError(f'Target disagreement in repeat {repeat}')
        for bank_no, bank in enumerate(BANKS, 1):
            lines += [
                r'\begin{longtable}{@{}lr*{4}{rrr}@{}}',
                rf'\caption{{Matched repeat {repeat}, Stage {bank_no}. All four methods passed and met all 25 targets.}}\\',
                *header, r'\endfirsthead', *header, r'\endhead',
                r'\bottomrule', r'\endlastfoot',
            ]
            for key in area.index:
                if key[0] != bank:
                    continue
                values = [key[1][5:8], str(targets.at[key, FINAL])]
                for method in METHODS:
                    values += [f'{area.at[key, method]:,}', str(delay.at[key, method]), f'{time.at[key, method]:.2f}']
                lines.append(' & '.join(values) + r' \\')
            lines.append(r'\end{longtable}')
    lines += [r'\endgroup', r'}']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify the tracked TeX without rewriting it')
    args = parser.parse_args()
    generated = render()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != generated:
            raise SystemExit(f'Casewise TeX is stale: {OUTPUT}')
    else:
        OUTPUT.write_text(generated, encoding='utf-8')
    print('Verified both repeats: four methods, 100 paired case rows, 400 observations.')


if __name__ == '__main__':
    main()
